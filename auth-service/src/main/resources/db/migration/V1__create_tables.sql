-- V1__create_tables.sql
-- auth-service: users, refresh_tokens

CREATE TABLE users (
                       id            BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                       email         VARCHAR(255) NOT NULL,
                       full_name     VARCHAR(255) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       phone_number  VARCHAR(255) NOT NULL,
                       role          VARCHAR(50)  NOT NULL DEFAULT 'CUSTOMER',
                       is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
                       created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       CONSTRAINT pk_users PRIMARY KEY (id),
                       CONSTRAINT uq_users_phone UNIQUE (phone_number),
                       CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'OPERATOR', 'ADMIN'))
);

CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

CREATE TABLE refresh_tokens (
                                id         BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                                user_id    BIGINT       NOT NULL,
                                token_hash VARCHAR(255) NOT NULL,
                                expires_at TIMESTAMPTZ  NOT NULL,
                                revoked_at TIMESTAMPTZ,
                                created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
                                CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
                                CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
                                CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at)
);

COMMENT ON COLUMN refresh_tokens.token_hash IS 'Bản băm (SHA-256) của refresh token, không lưu nguyên văn';
COMMENT ON COLUMN refresh_tokens.revoked_at IS 'Null nếu còn hiệu lực, có giá trị khi đã bị thu hồi';

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);