-- V1__create_tables.sql
-- trip-service: vehicle_types, seat_layouts, vehicles, trips

-- Cần cho exclusion constraint (so sánh bằng trên BIGINT trong chỉ mục gist)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- =========================
-- vehicle_types: loại xe
-- =========================
CREATE TABLE vehicle_types (
                               id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                               type_name       VARCHAR(255) NOT NULL,
                               seat_count      SMALLINT     NOT NULL,
                               description     TEXT,
                               is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
                               inactive_reason TEXT,
                               created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
                               updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
                               CONSTRAINT pk_vehicle_types PRIMARY KEY (id),
                               CONSTRAINT uq_vehicle_types_name UNIQUE (type_name),
                               CONSTRAINT ck_vehicle_types_seat_count CHECK (seat_count > 0)
);

-- =========================
-- seat_layouts: sơ đồ ghế theo loại xe
-- =========================
CREATE TABLE seat_layouts (
                              id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                              vehicle_type_id BIGINT       NOT NULL,
                              seat_code       VARCHAR(255) NOT NULL,
                              deck_no         SMALLINT     NOT NULL,
                              row_no          SMALLINT     NOT NULL,
                              col_no          SMALLINT     NOT NULL,
                              CONSTRAINT pk_seat_layouts PRIMARY KEY (id),
                              CONSTRAINT fk_seat_layouts_vehicle_type
                                  FOREIGN KEY (vehicle_type_id) REFERENCES vehicle_types (id),
                              CONSTRAINT uq_seat_layouts_code UNIQUE (vehicle_type_id, seat_code),
                              CONSTRAINT ck_seat_layouts_position
                                  CHECK (deck_no > 0 AND row_no > 0 AND col_no > 0)
);

COMMENT ON COLUMN seat_layouts.deck_no IS 'Tầng';
COMMENT ON COLUMN seat_layouts.row_no  IS 'Hàng, để định vị chỗ ngồi trong xe';
COMMENT ON COLUMN seat_layouts.col_no  IS 'Cột, để định vị chỗ ngồi trong xe';

-- =========================
-- vehicles: từng chiếc xe cụ thể
-- =========================
CREATE TABLE vehicles (
                          id               BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                          vehicle_type_id  BIGINT       NOT NULL,
                          license_plate    VARCHAR(255) NOT NULL,
                          model            VARCHAR(255),
                          manufacture_year INTEGER,
                          is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
                          inactive_reason  TEXT,
                          created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
                          updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
                          CONSTRAINT pk_vehicles PRIMARY KEY (id),
                          CONSTRAINT fk_vehicles_vehicle_type
                              FOREIGN KEY (vehicle_type_id) REFERENCES vehicle_types (id),
                          CONSTRAINT uq_vehicles_license_plate UNIQUE (license_plate),
                          CONSTRAINT ck_vehicles_manufacture_year
                              CHECK (manufacture_year IS NULL OR manufacture_year BETWEEN 1980 AND 2100)
);

CREATE INDEX idx_vehicles_vehicle_type ON vehicles (vehicle_type_id);

-- =========================
-- trips: chuyến xe cụ thể
-- route_id trỏ sang route-service nên KHÔNG có khóa ngoại
-- =========================
CREATE TABLE trips (
                       id                   BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                       route_id             BIGINT       NOT NULL,
                       vehicle_id           BIGINT       NOT NULL,
                       departure_at         TIMESTAMPTZ  NOT NULL,
                       estimated_arrival_at TIMESTAMPTZ  NOT NULL,
                       arrived_at           TIMESTAMPTZ,
                       price                BIGINT       NOT NULL,
                       status               VARCHAR(255) NOT NULL DEFAULT 'SCHEDULED',
                       cancel_reason        TEXT,
                       created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       CONSTRAINT pk_trips PRIMARY KEY (id),
                       CONSTRAINT fk_trips_vehicle
                           FOREIGN KEY (vehicle_id) REFERENCES vehicles (id),
                       CONSTRAINT ck_trips_price CHECK (price >= 0),
                       CONSTRAINT ck_trips_time  CHECK (estimated_arrival_at > departure_at),
                       CONSTRAINT ck_trips_status
                           CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    -- Một xe không chạy hai chuyến chồng giờ nhau (bỏ qua chuyến đã hủy)
                       CONSTRAINT ex_trips_vehicle_no_overlap
                           EXCLUDE USING gist (
            vehicle_id WITH =,
            tstzrange(departure_at, estimated_arrival_at) WITH &&
        ) WHERE (status <> 'CANCELLED')
);

COMMENT ON COLUMN trips.price      IS 'Giá vé, đơn vị VND';
COMMENT ON COLUMN trips.status     IS 'Mặc định SCHEDULED (đã lên lịch)';
COMMENT ON COLUMN trips.arrived_at IS 'Null cho tới khi xe cập bến, lúc đó mới cập nhật';

CREATE INDEX idx_trips_route_departure ON trips (route_id, departure_at);
CREATE INDEX idx_trips_vehicle         ON trips (vehicle_id);