-- V1__create_tables.sql
-- route-service: stations, rest_stops, routes, route_stops

-- =========================
-- stations: bến xe
-- =========================
CREATE TABLE stations (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(255) NOT NULL,
    province        VARCHAR(255) NOT NULL,
    district        VARCHAR(255) NOT NULL,
    coordinate      VARCHAR(255),
    full_address    TEXT         NOT NULL,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    inactive_reason TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_stations PRIMARY KEY (id)
);

CREATE INDEX idx_stations_province ON stations (province);

-- =========================
-- rest_stops: trạm dừng chân (đối tác)
-- =========================
CREATE TABLE rest_stops (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(255) NOT NULL,
    full_address    TEXT         NOT NULL,
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    inactive_reason TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_rest_stops PRIMARY KEY (id)
);

COMMENT ON COLUMN rest_stops.name         IS 'Tên của trạm dừng chân';
COMMENT ON COLUMN rest_stops.full_address IS 'Địa chỉ của trạm dừng chân';

-- =========================
-- routes: tuyến đường (bến đi -> bến đến, theo một đường cụ thể)
-- =========================
CREATE TABLE routes (
    id                BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    line              VARCHAR(255) NOT NULL,
    estimated_minutes INTEGER      NOT NULL,
    distance          REAL         NOT NULL,
    start_station_id  BIGINT       NOT NULL,
    end_station_id    BIGINT       NOT NULL,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    inactive_reason   TEXT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_routes PRIMARY KEY (id),
    CONSTRAINT fk_routes_start_station
        FOREIGN KEY (start_station_id) REFERENCES stations (id),
    CONSTRAINT fk_routes_end_station
        FOREIGN KEY (end_station_id) REFERENCES stations (id),
    CONSTRAINT ck_routes_different_stations
        CHECK (start_station_id <> end_station_id),
    CONSTRAINT ck_routes_estimated_minutes
        CHECK (estimated_minutes > 0),
    CONSTRAINT ck_routes_distance
        CHECK (distance > 0)
);

COMMENT ON COLUMN routes.line IS 'Tuyến đường sẽ đi (VD: cao tốc, quốc lộ 20,...)';
COMMENT ON COLUMN routes.estimated_minutes IS 'Thời gian ước tính chuyến đi, đơn vị phút';
COMMENT ON COLUMN routes.distance IS 'Khoảng cách, đơn vị kilometer';

-- Postgres không tự tạo index cho khóa ngoại
CREATE INDEX idx_routes_start_station ON routes (start_station_id);
CREATE INDEX idx_routes_end_station   ON routes (end_station_id);

-- Không cho trùng (bến đi, bến đến, đường đi) giữa các tuyến đang active
CREATE UNIQUE INDEX uq_routes_active_path
    ON routes (start_station_id, end_station_id, line)
    WHERE is_active;

-- =========================
-- route_stops: bảng nối giữa tuyến và trạm dừng chân
-- =========================
CREATE TABLE route_stops (
    id           BIGINT   NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    route_id     BIGINT   NOT NULL,
    rest_stop_id BIGINT   NOT NULL,
    stop_order   SMALLINT NOT NULL,
    rest_minutes SMALLINT NOT NULL,
    CONSTRAINT pk_route_stops PRIMARY KEY (id),
    CONSTRAINT fk_route_stops_route
        FOREIGN KEY (route_id) REFERENCES routes (id),
    CONSTRAINT fk_route_stops_rest_stop
        FOREIGN KEY (rest_stop_id) REFERENCES rest_stops (id),
    CONSTRAINT uq_route_stops_order
        UNIQUE (route_id, stop_order),
    CONSTRAINT uq_route_stops_rest_stop
        UNIQUE (route_id, rest_stop_id),
    CONSTRAINT ck_route_stops_order
        CHECK (stop_order > 0),
    CONSTRAINT ck_route_stops_rest_minutes
        CHECK (rest_minutes >= 0)
);

COMMENT ON COLUMN route_stops.stop_order   IS 'Thứ tự dừng trên tuyến, bắt đầu từ 1';
COMMENT ON COLUMN route_stops.rest_minutes IS 'Số phút dừng nghỉ tại trạm';

-- Tra ngược: trạm này thuộc những tuyến nào
CREATE INDEX idx_route_stops_rest_stop ON route_stops (rest_stop_id);